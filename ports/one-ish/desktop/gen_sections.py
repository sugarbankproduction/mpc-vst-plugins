#!/usr/bin/env python3
"""Writes build/desktop/sections.h for the desktop editor (desktop/editor.c) from params.json's "sections": each
panel's title and its parameters' VST indices, in file order, so a parameter added to a section shows up in the
window without touching the editor. Panels titled "MOD <n>" become the mod-matrix table instead of knob panels.
    python3 ports/one-ish/desktop/gen_sections.py <params.json> <out.h>"""
import json
import sys


def main():
    src, out = sys.argv[1], sys.argv[2]
    d = json.load(open(src, encoding="utf-8"))
    index = {p["key"]: i for i, p in enumerate(d["params"])}
    lines = ["/* generated by ports/one-ish/desktop/gen_sections.py from params.json: do not edit */",
             "#pragma once",
             "typedef struct { const char *title; int n; const short *params; } section_t;"]
    rows = []
    for n, sec in enumerate(d["sections"]):
        keys = [k for k in sec["keys"] if k in index]
        missing = [k for k in sec["keys"] if k not in index]
        if missing:
            raise SystemExit("%s: section %r names unknown params %s" % (src, sec["label"], missing))
        lines.append("static const short SEC_%d[] = {%s};" % (n, ", ".join(str(index[k]) for k in keys)))
        rows.append('{"%s", %d, SEC_%d}' % (sec["label"].replace('"', '\\"'), len(keys), n))
    lines.append("static const section_t SECTIONS[] = {%s};" % ", ".join(rows))
    lines.append("#define NSECTIONS %d" % len(rows))
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
