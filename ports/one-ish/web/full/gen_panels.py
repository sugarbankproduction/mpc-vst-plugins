"""Writes web/site/panels.js, the rectangles the page's PANEL ZOOM frames, from the layout.h the build just generated
(desktop/gen_layout.py), so the page follows the panel when the layout changes. Run by web/full/build.sh:
    python gen_panels.py <layout.h> <panels.js>"""
import json
import re
import sys

MIN_AREA = 4000  # (smaller plates, as the ribbon's LINK plate, are not worth a camera move)


def main():
    with open(sys.argv[1], newline="", encoding="utf-8") as f:
        src = f.read()
    base_w = int(re.search(r"#define BASE_W (\d+)", src).group(1))
    base_h = int(re.search(r"#define BASE_H (\d+)", src).group(1))
    table = re.search(r"PANELS\[\] = \{(.*?)\};", src, re.S).group(1)
    panels = []
    for x, y, w, h, title, style in re.findall(r'\{(\d+), (\d+), (\d+), (\d+), "([^"]*)", (\d+), -?\d+\}', table):
        x, y, w, h = int(x), int(y), int(w), int(h)
        if style == "2" or w * h < MIN_AREA:  # (a caption: a heading, not a panel)
            continue
        panels.append({"x": x, "y": y, "w": w, "h": h, "title": title.replace("|", " / ")})
    if not panels:
        raise SystemExit("gen_panels.py: no panels found in " + sys.argv[1])
    # the keyboard is not a panel in the layout: its two zones, up to the plate at the ribbon's left end
    keys = [int(v) for v in re.search(r"ZONE_KEYS\[4\] = \{(.*?)\}", src).group(1).split(",")]
    ribbon = [int(v) for v in re.search(r"ZONE_RIBBON\[4\] = \{(.*?)\}", src).group(1).split(",")]
    top = ribbon[1] - 2
    panels.append({"x": keys[0], "y": top, "w": keys[2], "h": keys[1] + keys[3] - top, "title": "KEYBOARD", "keys": True})
    text = "// Generated by web/full/gen_panels.py from desktop/gen_layout.py's layout; don't edit.\n"
    text += "export const BASE_W = %d, BASE_H = %d;\n" % (base_w, base_h)
    text += "export const PANELS = %s;\n" % json.dumps(panels)
    with open(sys.argv[2], "w", newline="", encoding="utf-8") as f:
        f.write(text)


main()
